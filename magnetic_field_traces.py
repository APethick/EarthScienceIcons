def design(kind):
    d=reference_drawing(kind)
    bounds=(0,90,1040,755) if kind=='igrf' else (0,85,825,570)
    x0,y0,x1,y1=bounds
    scale=42/max(x1-x0,y1-y0)
    return place(Detail(),d,24-(x0+x1)*scale/2,24-(y0+y1)*scale/2,scale)
